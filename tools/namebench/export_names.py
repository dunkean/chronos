"""Export small, sorted Namebench name pools for the Chronos bootstrap fixture.

Reads the sibling world database strictly read-only (SQLite URI mode=ro&immutable=1; Namebench's
own NameDB.conn would switch the file to WAL mode, so it is never opened through that path).
Selections are deterministic SQL orderings or SHA-256 keyed samples, never ORDER BY RANDOM().
Fantasy surnames and towns come from Namebench's own FantasyGenerator with a fixed `random` seed.

Usage (Namebench virtual environment, run from anywhere):
  ../namebench/.venv/Scripts/python.exe tools/namebench/export_names.py ../namebench output/names/names.json
"""
import hashlib
import json
import random
import sqlite3
import sys
import unicodedata
from pathlib import Path

VERSION = "chronos-namebench-export-v1"
FORENAMES_PER_GENDER = 150
SURNAMES = 250
PLACES = 250


def sha256_file(path, chunk=1 << 22):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while block := f.read(chunk):
            h.update(block)
    return h.hexdigest()


def key(text):
    return hashlib.sha256(f"{VERSION}:{text}".encode()).hexdigest()


def clean(names):
    """NFC-normalize, strip, deduplicate and sort by code point (stable across platforms)."""
    out = {unicodedata.normalize("NFC", n).strip() for n in names}
    return sorted(n for n in out if n)


def ranked(conn, country, name_type, gender, limit):
    # Namebench's own preference: ranked (philipperemy) names first; min length 3 as in
    # NameDB.random_names. Ties on rank break by name.
    sql = ("SELECT name, MIN(rank) AS r FROM names WHERE country_iso=? AND name_type=? "
           + ("AND gender=? " if gender else "")
           + "AND rank IS NOT NULL AND length(name)>=3 GROUP BY name ORDER BY r, name LIMIT ?")
    params = [country, name_type] + ([gender] if gender else []) + [limit]
    return [row[0] for row in conn.execute(sql, params)]


def places(conn, country, limit):
    # Populated places (GeoNames class P, code PPL) of 1,000-30,000 inhabitants, sampled by a
    # SHA-256 key of the GeoNames id: small towns rather than present-day capitals.
    rows = conn.execute(
        "SELECT geoname_id, name FROM places WHERE country_iso=? AND feature_class='P' "
        "AND feature_code='PPL' AND population BETWEEN 1000 AND 30000", (country,)).fetchall()
    rows.sort(key=lambda r: key(f"place:{country}:{r[0]}"))
    chosen, seen = [], set()
    for _, name in rows:
        n = unicodedata.normalize("NFC", name).strip()
        if n and n not in seen:
            seen.add(n)
            chosen.append(n)
        if len(chosen) == limit:
            break
    return chosen, len(rows)


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    root, out = Path(sys.argv[1]).resolve(), Path(sys.argv[2])
    db_path = root / "data" / "names.db"
    sys.path.insert(0, str(root))
    from namegen.db import NameDB
    from namegen.strategies.fantasy import FantasyGenerator

    conn = sqlite3.connect(f"file:{db_path.as_posix()}?mode=ro&immutable=1", uri=True)
    conn.row_factory = sqlite3.Row
    db = NameDB(db_path)
    db._conn = conn  # read-only connection; skips NameDB's WAL pragma

    pools, details = {}, {}
    # Contract key -> Namebench style (resolved by namegen.styles.StyleRegistry on 2026-10-21).
    for culture, style, country in (("french", "style.french", "FR"), ("british", "style.english_uk", "GB")):
        male = ranked(conn, country, "forename", "M", FORENAMES_PER_GENDER)
        female = ranked(conn, country, "forename", "F", FORENAMES_PER_GENDER)
        surnames = ranked(conn, country, "surname", None, SURNAMES)
        town, available = places(conn, country, PLACES)
        pools[culture] = {
            "forenames": clean(male + female), "surnames": clean(surnames), "places": clean(town),
            "forenames_male": clean(male), "forenames_female": clean(female),
        }
        details[culture] = {
            "namebench_style": style, "country_iso": country,
            "forenames": f"top {FORENAMES_PER_GENDER} per gender by present-day popularity rank (philipperemy), length>=3",
            "surnames": f"top {SURNAMES} by popularity rank (philipperemy), length>=3",
            "places": f"{PLACES} GeoNames PPL places of 1,000-30,000 inhabitants, SHA-256 keyed sample of {available}",
        }

    # Fantasy: Namebench 'fantasy.medievals' forename arrays (nm2 male, nm4 female; nm1/nm3 are
    # titles), sampled by SHA-256 key; surnames and towns generated by Namebench's FantasyGenerator.
    medieval = db.get_fantasy_arrays("fantasy.medievals")
    def sample(values, label, limit):
        values = clean(values)
        return sorted(sorted(values, key=lambda v: key(f"{label}:{v}"))[:limit])
    male = sample(medieval["nm2"], "fantasy:male", FORENAMES_PER_GENDER)
    female = sample(medieval["nm4"], "fantasy:female", FORENAMES_PER_GENDER)
    random.seed(f"{VERSION}:fantasy:surname")
    surnames = FantasyGenerator(db, "dungeon_and_dragons.humans").generate("surname", SURNAMES)
    random.seed(f"{VERSION}:fantasy:place")
    towns = FantasyGenerator(db, "towns_and_cities.fantasy_towns").generate("place", PLACES)
    pools["fantasy"] = {
        "forenames": clean(male + female), "surnames": clean(surnames), "places": clean(towns),
        "forenames_male": male, "forenames_female": female,
    }
    details["fantasy"] = {
        "namebench_style": "fantasy.medievals; dungeon_and_dragons.humans; towns_and_cities.fantasy_towns",
        "forenames": f"{FORENAMES_PER_GENDER} per gender, SHA-256 keyed sample of fantasy.medievals arrays nm2 ({len(medieval['nm2'])}) / nm4 ({len(medieval['nm4'])})",
        "surnames": f"FantasyGenerator('dungeon_and_dragons.humans').generate('surname', {SURNAMES}) after random.seed('{VERSION}:fantasy:surname')",
        "places": f"FantasyGenerator('towns_and_cities.fantasy_towns').generate('place', {PLACES}) after random.seed('{VERSION}:fantasy:place')",
    }
    for culture, pool in pools.items():
        details[culture]["counts"] = {k: len(v) for k, v in pool.items()}

    code = {p: sha256_file(root / p) for p in ("namegen/db.py", "namegen/styles.py", "namegen/strategies/fantasy.py", "namegen/onomastic_zones.json")}
    result = {
        "schema": "chronos-namebench-pools-v1", "generator": VERSION,
        "python": sys.version.split()[0],
        "database": {"file": "namebench/data/names.db", "sha256": sha256_file(db_path), "bytes": db_path.stat().st_size},
        "code_sha256": code, "selection": details, "pools": pools,
        "limitations": "Present-day name frequencies and GeoNames places; no historical authenticity. Fantasy generator output depends on Python's random implementation and the database arrays.",
    }
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(result, ensure_ascii=False, indent=1, sort_keys=True), encoding="utf-8")
    print(f"wrote {out}: " + ", ".join(f"{c} {details[c]['counts']}" for c in pools))


if __name__ == "__main__":
    main()
